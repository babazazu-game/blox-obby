import { core } from './core.ts';
import { RU } from './locale/ru.ts';
import { EN } from './locale/en.ts';

/**
 * Язык интерфейса.
 *
 * Определяется АВТОМАТИЧЕСКИ и только автоматически: из SDK площадки, а на
 * локальной машине — из настроек браузера. Ручного переключателя в игре нет
 * и не будет. Так требует п. 2.14: язык должен быть выбран ДО первого кадра
 * интерфейса. Предыдущий проект этого разработчика получил замечание
 * модерации именно за переключение постфактум — оно читается как «игра
 * сначала показала не тот язык».
 *
 * Отсюда порядок запуска в main.ts: сначала `core.ready`, потом Phaser.
 * К моменту, когда первая сцена что-то рисует, `t()` уже отвечает на нужном
 * языке, и перерисовывать ничего не приходится.
 */

core.i18n.register('ru', RU);
core.i18n.register('en', EN);

/**
 * `?lang=en` в адресе перебивает автоопределение.
 *
 * Это не ручной переключатель и правилу 2.14 не противоречит: язык всё так же
 * выбран ДО первого кадра, просто источник другой. Сама площадка открывает
 * игру именно так — `lang` приходит у неё в адресе, — поэтому поддержать его
 * надо в любом случае.
 *
 * Заодно это единственный быстрый способ снять скриншоты английской версии:
 * иначе пришлось бы менять язык всего браузера и перезапускать его.
 */
function applyLangFromUrl(): void {
  if (typeof location === 'undefined') return;
  const asked = new URLSearchParams(location.search).get('lang');
  if (asked === 'ru' || asked === 'en') core.i18n.setLang(asked);
}

// Дважды, и это не перестраховка. При импорте — чтобы язык стоял с первой
// строки. После `core.ready` — потому что каркас на этом шаге сам ставит язык
// (из SDK или из браузера) и затирает всё, что стояло до него.
applyLangFromUrl();
void core.ready.then(applyLangFromUrl);

/**
 * Строка на текущем языке. `{имя}` в словаре подставляется из `vars`.
 *
 * Отсутствующий ключ возвращается как есть, а не пустой строкой: пустое место
 * в интерфейсе выглядит как недоделка (п. 1.15), а торчащий `menu.play`
 * бросается в глаза при первом же прогоне.
 */
export const t = (key: string, vars?: Record<string, string | number>): string =>
  core.i18n.t(key, vars);

export const lang = (): 'ru' | 'en' => core.i18n.current;

/**
 * Множественное число для счётных строк.
 *
 * У русского три формы (1 ход, 2 хода, 5 ходов), у английского две. Держать
 * это в самих словарях нельзя: правило зависит от языка, а не от строки.
 * Поэтому словарь даёт формы через `|`, а выбор делается здесь.
 *
 * Проверять надо именно на 11–14: они кончаются на 1, 2, 3, 4, но берут
 * форму множественного числа. Без этой проверки получается «11 ход».
 */
export function plural(key: string, n: number): string {
  const forms = t(key).split('|');
  if (lang() !== 'ru') return forms[n === 1 ? 0 : 1] ?? forms[0];

  const hundred = n % 100;
  const ten = n % 10;
  const index = hundred > 4 && hundred < 21 ? 2
    : ten === 1 ? 0
    : ten >= 2 && ten <= 4 ? 1
    : 2;
  return forms[index] ?? forms[0];
}
